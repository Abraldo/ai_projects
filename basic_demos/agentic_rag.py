"""## **7. Assemble The Graph**

"""

from langgraph.graph import StateGraph, START, END
from langgraph.prebuilt import ToolNode
from langgraph.prebuilt import tools_condition

workflow = StateGraph(MessagesState)

# Define the nodes we will cycle between
workflow.add_node('search query generator', generate_query_or_respond)
workflow.add_node("retrieve", ToolNode([retriever_tool]))
workflow.add_node('rewriter', rewrite_question)
workflow.add_node('answer genretor', generate_answer)

workflow.add_edge(START, "search query generator")

# Decide whether to retrieve
workflow.add_conditional_edges(
    "search query generator",
    # Assess LLM decision (call `retriever_tool` tool or respond to the user)
    tools_condition,
    {
        # Translate the condition outputs to nodes in our graph
        "tools": "retrieve",
        END: END,
    },
)

# Edges taken after the `action` node is called.
workflow.add_conditional_edges(
    "retrieve",
    # Assess agent decision
    grade_documents,
    {
        "generate_answer": "answer genretor",
        "rewrite_question": "rewriter",
    }
)
workflow.add_edge("answer genretor", END)
workflow.add_edge("rewriter", "search query generator")

# Compile
graph = workflow.compile()

